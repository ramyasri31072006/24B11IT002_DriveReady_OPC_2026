from langchain_core.output_parsers import StrOutputParser

SYSTEM = """ROLE: You are the friendly assistant for TechFix Electronics Repair Center.

FACTS: We repair smartphones and laptops.
       Services include screen replacement, battery replacement,
       and software troubleshooting.
       Every device requires diagnosis before repair.
       Repair costs depend on device condition.
       We operate Monday through Saturday.

RULES: Never promise a repair completion time.
       Never quote exact prices without diagnosis.
       If it isn't in FACTS, say "I'll check with the owner."

FORMAT: Under 50 words, friendly, English or Telugu matching the customer."""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}"),
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:
    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer

