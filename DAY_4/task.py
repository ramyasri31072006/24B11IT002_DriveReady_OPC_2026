from typing import Literal
from pydantic import BaseModel, Field
from langchain.tools import tool

SERVICES = {
    "screen replacement": 1500,
    "battery replacement": 1000,
    "software troubleshooting": 500
}

HOURS = {
    "monday": "Open",
    "tuesday": "Open",
    "wednesday": "Open",
    "thursday": "Open",
    "friday": "Open",
    "saturday": "Open",
    "sunday": "Closed"
}


class RepairRequest(BaseModel):
    """A repair request taken from a customer's chat message."""

    name: str = Field(
        description="Customer's first name",
        min_length=1
    )

    device: Literal["smartphone", "laptop"] = Field(
        description="Customer's device type"
    )

    service: Literal[
        "screen replacement",
        "battery replacement",
        "software troubleshooting"
    ] = Field(description="Required repair service")

    qty: int = Field(
        description="Number of devices",
        ge=1
    )

    date: str = Field(
        description="Preferred visit date",
        min_length=1
    )

    problem: str = Field(
        description="Problem reported by the customer",
        min_length=1
    )

@tool
def get_estimated_price(service: str, qty: int = 1) -> str:
    """Get the estimated repair cost in rupees.

    Args:
        service: Required repair service
        qty: Number of devices
    """

    service = service.lower().strip()

    price = SERVICES.get(service)

    if price is None:
        return f"Service not available. We offer: {', '.join(SERVICES)}."

    if qty < 1:
        return "Quantity must be at least 1."

    return (
        f"{qty} x {service} = Rs {price * qty} estimated. "
        "Final cost depends on device diagnosis."
    )


@tool
def is_open(day: str) -> str:
    """Check whether TechFix is open on a given day."""

    status = HOURS.get(day.lower().strip())

    if status is None:
        return f"'{day}' is not a valid day of the week."

    return f"TechFix is {status.lower()} on {day}."


@tool
def log_repair(
    name: str,
    device: str,
    service: str,
    qty: int,
    date: str,
    problem: str
) -> str:
    """Save a confirmed repair request to Google Sheets.

    Use only after the customer confirms their repair request
    and provides all required details.
    """

    try:
        repair = RepairRequest(
            name=name,
            device=device.lower().strip(),
            service=service.lower().strip(),
            qty=qty,
            date=date,
            problem=problem
        )

    except Exception as e:
        return f"Could not save the repair request: {e}"

    total = SERVICES[repair.service] * repair.qty

    ws.append_row([
        repair.name,
        repair.device,
        repair.service,
        repair.qty,
        repair.date,
        repair.problem,
        total
    ])

    return (
        f"Repair request saved for {repair.name}. "
        f"Device: {repair.device}. "
        f"Service: {repair.service}. "
        f"Quantity: {repair.qty}. "
        f"Preferred visit: {repair.date}. "
        f"Estimated cost: Rs {total}. "
        "Final cost depends on diagnosis."
    )

from langchain.agents import create_agent

SYSTEM = """ROLE: You are the friendly repair assistant
for TechFix Electronics Repair Center.

FACTS: We repair smartphones and laptops.
       Every device requires diagnosis before repair.
       Final repair costs depend on device condition.

RULES: Always use get_estimated_price for price estimates.
       Always use is_open for working days.
       Never guess prices or opening timings.
       Never guarantee repair completion times.
       Never confirm exact repair costs without diagnosis.
       Before log_repair, collect name, device, service,
       quantity, preferred visit date and device problem.
       Ask for missing details.
       Save only after customer confirmation.
       Do not treat a preferred visit date as a confirmed appointment.
       After saving, read back the repair request and estimated cost.
       If information is unavailable, say "I'll check with the owner."

FORMAT: Under 60 words, friendly, English or Telugu
matching the customer."""

agent = create_agent(
    model=llm,
    tools=[
        get_estimated_price,
        is_open,
        log_repair
    ],
    system_prompt=SYSTEM
)

history = []


def chat(text: str) -> str:
    global history

    try:
        result = agent.invoke({
            "messages": history + [
                {"role": "user", "content": text}
            ]
        })

        history = result["messages"]

        return history[-1].content

    except Exception as e:
        print("Agent error:", e)

        return (
            "Sorry, I'm a little busy. "
            "Please try again in a minute."
        )


